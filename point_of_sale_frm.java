    private void btnLookUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLookUpActionPerformed
        // TODO add your handling code here:  
        try{
            if(!txtMedicineID.getText().equals("")){
                if(!txtQuantity.getText().equals("")){
                    
                    CashierClass cc = new CashierClass();                  
                    
                    String medID = txtMedicineID.getText();
                    int qty = Integer.parseInt(txtQuantity.getText());
                    if(!cc.checkStockAvailability(qty, medID)){
                        JOptionPane.showMessageDialog(null, "Over-selling product, you have "+cc.getavailableSOH()+" SOH left, please replenish!", "Message", JOptionPane.ERROR_MESSAGE);
                    }else{
                        cc.cashier(medID, qty);
                        txtMedicineID_Dispaly.setText(cc.getMedID());
                        txtMedicineName.setText(cc.getMedName());
                        txtMedicineType.setText(cc.getMedType());
                        double price = cc.getPrice();
                        txtPrice.setText(String.valueOf(price));
                        btnAddToCart.setEnabled(true);
                    }
                    
                }else{
                    JOptionPane.showMessageDialog(null, "Quantity required!", "Message", JOptionPane.ERROR_MESSAGE);
                }
            }else{
                JOptionPane.showMessageDialog(null, "Medicine ID required!", "Message", JOptionPane.ERROR_MESSAGE);
            }
        }catch(NumberFormatException ex){
            JOptionPane.showMessageDialog(null, ex, "Message", JOptionPane.ERROR_MESSAGE);
        
        }
       
    }//GEN-LAST:event_btnLookUpActionPerformed

