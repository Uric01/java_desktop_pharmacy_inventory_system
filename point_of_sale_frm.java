    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        // TODO add your handling code here:
        try{
            if (!(txtMedicineName.getText().isEmpty()
                    || txtMedicineType.getText().isEmpty()
                    || txtPrice.getText().isEmpty()
                    || txtQuantity.getText().isEmpty())) {

                String medID;
                String medType;
                Double price;
                int qty;
                String name;

                medID = txtMedicineID.getText();
                name = txtMedicineName.getText();
                medType = txtMedicineType.getText();
                price = Double.valueOf(txtPrice.getText());
                qty = Integer.parseInt(txtQuantity.getText());
                billing = new BillingClass(name);

                billing.setMedID(medID);
                billing.setName(name);
                billing.setMedType(medType);
                billing.setPrice(price);
                billing.setQty(qty);

                cart.add(billing);

                DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
                model.addRow(new Object[]{billing.getMedID(),
                    billing.getName(),
                    billing.getMedType(),
                    billing.getPrice(),
                    billing.getQty()});

                NumberFormat currencyFormat = NumberFormat.getCurrencyInstance();

                for (BillingClass items : cart) {

                    totalAmount += items.getPrice() * items.getQty();
                }

                txtTotalAmount.setText(currencyFormat.format(totalAmount));
                btnCheckOut.setEnabled(true);


            } else {
                JOptionPane.showMessageDialog(null, "Please ensure no data is removed from the fields!", "Message", JOptionPane.ERROR_MESSAGE);
            }
        
        }catch(HeadlessException | NumberFormatException ex){
            JOptionPane.showMessageDialog(null, ex,"Message",JOptionPane.ERROR_MESSAGE);       
        
        }
        
    }//GEN-LAST:event_btnAddToCartActionPerformed

